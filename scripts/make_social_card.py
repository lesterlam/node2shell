#!/usr/bin/env python3
"""Render the 1280x640 GitHub social-preview card for this repo.

Text is drawn with Pillow rather than generated by a model: the card states exact
numbers (offsets, byte counts) and a single wrong digit would misrepresent the
findings. Output: assets/social-preview.png
"""
from PIL import Image, ImageDraw, ImageFont

W, H = 1280, 640
BG = (11, 13, 18)
PANEL = (19, 23, 34)
LINE = (42, 50, 68)
INK = (230, 233, 242)
DIM = (139, 147, 167)
OK = (61, 220, 132)
HOT = (255, 93, 93)
WARN = (255, 180, 84)
INFO = (92, 200, 255)
F = "/usr/share/fonts/truetype/dejavu/"
f = lambda n, s: ImageFont.truetype(F + n, s)
F_TITLE = f("DejaVuSans-Bold.ttf", 52)
F_SUB = f("DejaVuSans.ttf", 25)
F_CHIP = f("DejaVuSansMono-Bold.ttf", 19)
F_LBL = f("DejaVuSansMono-Bold.ttf", 15)
F_SM = f("DejaVuSansMono.ttf", 15)
F_TINY = f("DejaVuSansMono.ttf", 14)

img = Image.new("RGB", (W, H), BG)
d = ImageDraw.Draw(img)
d.rounded_rectangle([16, 16, W - 16, H - 16], 18, outline=LINE, width=2)

# ---- title block ---------------------------------------------------------
d.text((56, 48), "Node2Shell", font=F_TITLE, fill=INK)
w = d.textlength("Node2Shell", font=F_TITLE)
d.text((56 + w + 18, 48), "CVE-2026-111497", font=F_TITLE, fill=INFO)
d.text((56, 116), "Brotli decoder out-of-bounds write  ·  independent reproduction, primary sources only",
       font=F_SUB, fill=DIM)

# ---- verdict chips -------------------------------------------------------
chips = [
    ("trigger reproduced", OK),
    ("OOB write: 16 B past the 8-byte buffer", OK),
    ("100% CPU spin (DoS)", WARN),
    ("pointer control: unreachable", HOT),
    ("RCE: not reproduced", HOT),
]
x, y = 56, 176
for label, col in chips:
    tw = d.textlength(label, font=F_CHIP)
    cw = tw + 40
    if x + cw > W - 56:
        x, y = 56, y + 56
    d.rounded_rectangle([x, y, x + cw, y + 42], 21, outline=col, width=2)
    d.ellipse([x + 14, y + 17, x + 22, y + 25], fill=col)
    d.text((x + 30, y + 9), label, font=F_CHIP, fill=col)
    x += cw + 14

# ---- memory map ----------------------------------------------------------
MAP_Y, MAP_H = 320, 210
X0, X1 = 56, W - 56
LO, HI = 64, 176                      # offsets shown
px = (X1 - X0) / (HI - LO)
sx = lambda o: X0 + (o - LO) * px

FIELDS = [
    (72, 8, "buffer.u8[8]", (35, 48, 71)),
    (80, 8, "buffer_length", (60, 36, 48)),
    (88, 4, "pos", (44, 34, 51)),
    (92, 4, "", (18, 21, 29)),
    (96, 4, "max_distance", (44, 34, 51)),
    (100, 4, "ringbuffer_size", (26, 31, 44)),
    (104, 4, "ringbuf_mask", (26, 31, 44)),
    (108, 4, "", (18, 21, 29)),
    (112, 16, "dist_rb[4]", (26, 31, 44)),
    (128, 4, "", (18, 21, 29)),
    (132, 4, "mlr", (26, 31, 44)),
    (136, 8, "ringbuffer", (18, 40, 58)),
    (144, 8, "ringbuffer_end", (18, 40, 58)),
    (152, 8, "htree_command", (18, 40, 58)),
    (160, 16, "", (18, 21, 29)),
]
d.text((X0, MAP_Y - 34), "decoder state  ·  offset 72 + attacker byte index", font=F_SM, fill=DIM)

for off, size, name, col in FIELDS:
    a, b = sx(off), sx(off + size)
    d.rectangle([a, MAP_Y, b - 1, MAP_Y + MAP_H], fill=col, outline=(11, 13, 18))
    if name:
        t = Image.new("RGBA", (F_LBL.getbbox(name)[2] + 8, 22), (0, 0, 0, 0))
        ImageDraw.Draw(t).text((0, 0), name, font=F_LBL, fill=INK)
        t = t.rotate(90, expand=True)
        img.paste(t, (int(a + (b - a - t.width) / 2), MAP_Y + MAP_H - t.height - 6), t)

# red overlay: the bytes actually written
hi = sx(98)
ov = Image.new("RGBA", (int(hi - sx(72)), MAP_H), (255, 93, 93, 60))
img.paste(ov, (int(sx(72)), MAP_Y), ov)
d.line([hi, MAP_Y, hi, MAP_Y + MAP_H], fill=WARN, width=3)
# ceiling label sits left of the line so it cannot collide with the hatched-zone caption
d.text((hi - 12 - d.textlength("ceiling: offset 98", font=F_LBL), MAP_Y + 8),
       "ceiling: offset 98", font=F_LBL, fill=WARN)
d.text((sx(72) + 6, MAP_Y + MAP_H + 8), "bytes written by the OOB copy", font=F_TINY, fill=HOT)

# hatched unreachable region
hat = Image.new("RGBA", (int(sx(176) - sx(103)), MAP_H), (0, 0, 0, 0))
hd = ImageDraw.Draw(hat)
for i in range(-MAP_H, hat.width, 14):
    hd.line([i, MAP_H, i + MAP_H, 0], fill=(255, 93, 93, 34), width=6)
img.paste(hat, (int(sx(103)), MAP_Y), hat)
d.line([sx(103), MAP_Y, sx(103), MAP_Y + MAP_H], fill=(120, 60, 60), width=2)
d.text((sx(106), MAP_Y + 8), "unreachable from the input buffer", font=F_LBL, fill=(255, 157, 157))

# ---- footer --------------------------------------------------------------
d.text((56, 566), "2²⁴ commands × 11 bits = 23 068 672-byte payload   ·   Brotli 1.2.0 vs 1.2.1 A/B",
       font=F_TINY, fill=DIM)
d.text((56, 590), "github.com/lesterlam/node2shell", font=F_SM, fill=INFO)
lab = "lesterlam.github.io/node2shell"
d.text((W - 56 - d.textlength(lab, font=F_SM), 590), lab, font=F_SM, fill=DIM)

import os, pathlib
out = pathlib.Path(__file__).resolve().parent.parent / "assets" / "social-preview.png"
out.parent.mkdir(parents=True, exist_ok=True)
img.save(out, "PNG", optimize=True)
print("wrote", out, os.path.getsize(out), "bytes", img.size)
